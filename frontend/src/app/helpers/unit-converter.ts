export function convertUnit(value: number, from: string, to: string): number {
  from = from.replace(/ /g, '_');
  to = to.replace(/ /g, '_');

  if (conversions[from] && conversions[from][to]) {
    return parseFloat((value * conversions[from][to]).toFixed(4));
  } else {
    return value;
  }
}
